-- Additive, opt-in Envers pilot. Existing business data and global audit are unchanged.
CREATE TABLE envers_poc_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at_epoch_ms BIGINT NOT NULL,
    actor_kind VARCHAR(20) NOT NULL,
    actor_person_id UUID,
    actor_platform_account_id UUID,
    request_id VARCHAR(100),
    CONSTRAINT envers_poc_revision_actor_shape CHECK (
        (actor_kind = 'INSTITUTION' AND actor_person_id IS NOT NULL AND actor_platform_account_id IS NULL)
        OR (actor_kind = 'PLATFORM' AND actor_person_id IS NULL AND actor_platform_account_id IS NOT NULL)
        OR (actor_kind = 'ANONYMOUS' AND actor_person_id IS NULL AND actor_platform_account_id IS NULL)
    )
);

CREATE TABLE envers_poc_shifts_aud (
    shift_id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES envers_poc_revisions(id),
    revtype SMALLINT NOT NULL CHECK (revtype IN (0, 1, 2)),
    institution_id UUID,
    name VARCHAR(150),
    active BOOLEAN,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    name_mod BOOLEAN,
    active_mod BOOLEAN,
    PRIMARY KEY (shift_id, rev)
);

CREATE TABLE envers_poc_courses_aud (
    course_id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES envers_poc_revisions(id),
    revtype SMALLINT NOT NULL CHECK (revtype IN (0, 1, 2)),
    institution_id UUID,
    study_plan_space_id UUID,
    instrument_id UUID,
    academic_year_id UUID,
    status VARCHAR(20),
    status_mod BOOLEAN,
    deleted_at TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (course_id, rev)
);

CREATE TABLE envers_poc_course_classes_aud (
    course_class_id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES envers_poc_revisions(id),
    revtype SMALLINT NOT NULL CHECK (revtype IN (0, 1, 2)),
    institution_id UUID,
    course_id UUID,
    class_number INTEGER,
    PRIMARY KEY (course_class_id, rev)
);

CREATE TABLE envers_poc_course_class_teachers_aud (
    course_class_teacher_id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES envers_poc_revisions(id),
    revtype SMALLINT NOT NULL CHECK (revtype IN (0, 1, 2)),
    institution_id UUID,
    course_class_id UUID,
    person_id UUID,
    PRIMARY KEY (course_class_teacher_id, rev)
);

CREATE TABLE envers_poc_course_class_days_aud (
    course_class_day_id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES envers_poc_revisions(id),
    revtype SMALLINT NOT NULL CHECK (revtype IN (0, 1, 2)),
    institution_id UUID,
    course_class_id UUID,
    day_of_week VARCHAR(20),
    capacity INTEGER,
    period_duration_minutes INTEGER,
    PRIMARY KEY (course_class_day_id, rev)
);

CREATE TABLE envers_poc_course_class_schedules_aud (
    course_class_schedule_id UUID NOT NULL,
    rev BIGINT NOT NULL REFERENCES envers_poc_revisions(id),
    revtype SMALLINT NOT NULL CHECK (revtype IN (0, 1, 2)),
    institution_id UUID,
    course_class_day_id UUID,
    start_time TIME(6),
    end_time TIME(6),
    PRIMARY KEY (course_class_schedule_id, rev)
);

CREATE INDEX envers_poc_shifts_institution_rev_idx ON envers_poc_shifts_aud(institution_id, rev);
CREATE INDEX envers_poc_courses_institution_rev_idx ON envers_poc_courses_aud(institution_id, rev);
CREATE INDEX envers_poc_classes_course_rev_idx ON envers_poc_course_classes_aud(course_id, rev);
CREATE INDEX envers_poc_teachers_class_rev_idx ON envers_poc_course_class_teachers_aud(course_class_id, rev);
CREATE INDEX envers_poc_days_class_rev_idx ON envers_poc_course_class_days_aud(course_class_id, rev);
CREATE INDEX envers_poc_schedules_day_rev_idx ON envers_poc_course_class_schedules_aud(course_class_day_id, rev);
